"""
Phase 7 training data pipeline.

Order of operations (strict, leakage-avoiding)
----------------------------------------------
1. **Load** the persisted dataset with the Phase 4 loader
   (:func:`dataset.loader.load_dataset`) — the dataset is an engineering
   artifact, never regenerated by the training code.
2. **Split by user first**: the outer split keeps every user represented in
   both training and test sessions (:func:`dataset.split.split_train_test`).
3. **Split training again into train/validation** (same per-user logic).
   Sessions are never moved between partitions afterwards.
4. **Pairs are generated *after* the split**, within each partition only
   (Phase 6 :func:`ml.verification.pairs.generate_pairs`). A pair never mixes
   sessions from two partitions, so no train/validation/test leakage is
   possible by construction.
5. The **FeatureScaler is fitted on training sessions only** and reused for
   validation/test (Phase 3 normalization contract).

The PyTorch :class:`SiamesePairDataset` yields ``(session_a, session_b,
label)`` per item; a custom collate keeps the two session lists and a label
tensor. Identity fields (``user_id`` / ``session_id``) are metadata only —
they are used to build labels and to audit leakage, never as model features
(the Siamese verifier reads exclusively ``keyboard_sequence`` /
``mouse_sequence``).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict, List, Mapping, Sequence, Tuple

import torch
from torch.utils.data import DataLoader, Dataset

from dataset import (
    KEYBOARD_FEATURE_COLUMNS,
    MOUSE_FEATURE_COLUMNS,
    load_dataset,
    split_train_test,
)
from ml.preprocessing import FeatureScaler, sequence_to_rows
from ml.verification import VerificationPair, generate_pairs

from .config import TrainingConfig

Batch = Tuple[List[Dict[str, Any]], List[Dict[str, Any]], torch.Tensor]


@dataclass(frozen=True)
class TrainingData:
    """Everything materialized from the persisted dataset for one run.

    All partition/pairing decisions are stored so training and tests can audit
    exactly how a run was built (train/val/test session ids, pair metadata).
    """

    train_sessions: List[Dict[str, Any]]
    val_sessions: List[Dict[str, Any]]
    test_sessions: List[Dict[str, Any]]
    train_pairs: List[VerificationPair]
    val_pairs: List[VerificationPair]
    test_pairs: List[VerificationPair]
    keyboard_scaler: FeatureScaler
    mouse_scaler: FeatureScaler

    def session_count_summary(self) -> Dict[str, int]:
        return {
            "train_sessions": len(self.train_sessions),
            "val_sessions": len(self.val_sessions),
            "test_sessions": len(self.test_sessions),
        }

    def pair_count_summary(self) -> Dict[str, int]:
        def counts(pairs: Sequence[VerificationPair]) -> Dict[str, int]:
            genuine = sum(1 for p in pairs if p.label == 1)
            return {
                "genuine": genuine,
                "impostor": len(pairs) - genuine,
                "total": len(pairs),
            }

        return {
            "train": counts(self.train_pairs),
            "val": counts(self.val_pairs),
            "test": counts(self.test_pairs),
        }


def _flatten_rows(sessions: Sequence[Mapping[str, Any]], feature_columns: Sequence[str], modality: str) -> List[List[float]]:
    rows: List[List[float]] = []
    for session in sessions:
        sequence = session.get(modality + "_sequence", [])
        rows.extend(sequence_to_rows(sequence, feature_columns))
    return rows


def _fit_scalers(train_sessions: Sequence[Mapping[str, Any]]) -> Tuple[FeatureScaler, FeatureScaler]:
    keyboard_rows = _flatten_rows(train_sessions, KEYBOARD_FEATURE_COLUMNS, "keyboard")
    mouse_rows = _flatten_rows(train_sessions, MOUSE_FEATURE_COLUMNS, "mouse")
    if not keyboard_rows:
        raise ValueError("no keyboard rows available in the training partition; cannot fit the keyboard scaler")
    if not mouse_rows:
        raise ValueError("no mouse rows available in the training partition; cannot fit the mouse scaler")
    return (
        FeatureScaler(list(KEYBOARD_FEATURE_COLUMNS)).fit(keyboard_rows),
        FeatureScaler(list(MOUSE_FEATURE_COLUMNS)).fit(mouse_rows),
    )


def _verify_user_partition_coverage(partitions: Sequence[Sequence[Mapping[str, Any]]]) -> None:
    """Every user must appear in every partition (per-user isolation policy)."""
    users = {e["user_id"] for e in partitions[0]}
    for i, partition in enumerate(partitions[1:], start=1):
        partition_users = {e["user_id"] for e in partition}
        if partition_users != users:
            raise ValueError(
                "partition coverage mismatch: partition 0 users {} != partition {} users {}".format(
                    sorted(users), i, sorted(partition_users)
                )
            )


def prepare_training_data(config: TrainingConfig) -> TrainingData:
    """Build train/val/test sessions, per-partition pairs, and fitted scalers.

    The dataset is loaded from ``config.dataset_path`` and must already exist
    (persisted Phase 4 artifact — it is never regenerated here).

    Raises:
        ValueError: if the number of available genuine/impostor candidates in a
            partition is smaller than the requested pair count (users with too
            few sessions), or whenever leakage would otherwise be possible.
    """
    entries = load_dataset(config.dataset_path)

    train_outer, test = split_train_test(
        entries, seed=config.seed, train_fraction=config.train_fraction, min_train=1, min_test=1
    )
    if config.val_fraction >= 1.0:
        raise ValueError("val_fraction must be < 1 so a training partition remains")
    train, val = split_train_test(
        train_outer,
        seed=config.seed + 1,
        train_fraction=1.0 - config.val_fraction,
        min_train=1,
        min_test=1,
    )

    if {e["session_id"] for e in train} & {e["session_id"] for e in val}:
        raise ValueError("train/val session leakage detected")
    if {e["session_id"] for e in train_outer} & {e["session_id"] for e in test}:
        raise ValueError("train/test session leakage detected")
    _verify_user_partition_coverage((train, val, test))

    keyboard_scaler, mouse_scaler = _fit_scalers(train)

    train_pairs = generate_pairs(
        train, n_genuine=config.n_genuine_train, n_impostor=config.n_impostor_train, seed=config.seed
    )
    val_pairs = generate_pairs(
        val, n_genuine=config.n_genuine_val, n_impostor=config.n_impostor_val, seed=config.seed + 1
    )
    test_pairs = generate_pairs(
        test, n_genuine=config.n_genuine_test, n_impostor=config.n_impostor_test, seed=config.seed + 2
    )

    return TrainingData(
        train_sessions=list(train),
        val_sessions=list(val),
        test_sessions=list(test),
        train_pairs=train_pairs,
        val_pairs=val_pairs,
        test_pairs=test_pairs,
        keyboard_scaler=keyboard_scaler,
        mouse_scaler=mouse_scaler,
    )


class SiamesePairDataset(Dataset):
    """PyTorch dataset of ``(session_a, session_b, label)`` Siamese pairs.

    Each item mirrors a :class:`~ml.verification.VerificationPair`. Identity
    fields stay inside the session dicts as metadata — the Siamese verifier
    never reads them, and no feature tensor is built here.
    """

    def __init__(self, pairs: Sequence[VerificationPair]) -> None:
        if not isinstance(pairs, (list, tuple)):
            raise TypeError("pairs must be a list/tuple of VerificationPair, got {!r}".format(type(pairs).__name__))
        if not all(isinstance(p, VerificationPair) for p in pairs):
            raise TypeError("every item must be a VerificationPair")
        self.pairs = list(pairs)

    def __len__(self) -> int:
        return len(self.pairs)

    def __getitem__(self, index: int) -> Tuple[Dict[str, Any], Dict[str, Any], int]:
        pair = self.pairs[index]
        return pair.session_a, pair.session_b, int(pair.label)


def siamese_collate(batch: Sequence[Tuple[Dict[str, Any], Dict[str, Any], int]]) -> Batch:
    """Collate ``(session_a, session_b, label)`` items into model-ready inputs.

    Returns ``(sessions_a, sessions_b, labels)`` where the two session lists
    are consumed by :class:`~ml.verification.SiameseVerifier.forward` and
    ``labels`` is a ``torch.long`` tensor ``[B]`` matching the Phase 6 label
    convention (``1`` genuine / ``0`` impostor).
    """
    if not batch:
        raise ValueError("cannot collate an empty batch")
    sessions_a = [item[0] for item in batch]
    sessions_b = [item[1] for item in batch]
    labels = torch.tensor([item[2] for item in batch], dtype=torch.long)
    return sessions_a, sessions_b, labels


def make_torch_generator(seed: int) -> torch.Generator:
    """A CPU torch RNG used for deterministic, epoch-addressable shuffling."""
    generator = torch.Generator()
    generator.manual_seed(seed)
    return generator


def build_data_loaders(
    data: TrainingData,
    config: TrainingConfig,
    train_generator: torch.Generator,
) -> Tuple[DataLoader, DataLoader, DataLoader]:
    """Build (train, val, test) DataLoaders from the prepared partitions.

    - train:   shuffled each epoch via ``train_generator`` (the caller reseeds
        it per epoch; passing ``shuffle=True``).
    - val/test: never shuffled, never used by the training loop.
    - ``num_workers=0``: CPU validation expects single-process loading.
    """
    train_loader = DataLoader(
        SiamesePairDataset(data.train_pairs),
        batch_size=config.batch_size,
        shuffle=True,
        generator=train_generator,
        collate_fn=siamese_collate,
        num_workers=config.num_workers,
    )
    val_loader = DataLoader(
        SiamesePairDataset(data.val_pairs),
        batch_size=config.batch_size,
        shuffle=False,
        collate_fn=siamese_collate,
        num_workers=0,
    )
    test_loader = DataLoader(
        SiamesePairDataset(data.test_pairs),
        batch_size=config.batch_size,
        shuffle=False,
        collate_fn=siamese_collate,
        num_workers=0,
    )
    return train_loader, val_loader, test_loader


